"""Generate and check the counts that the roadmap and the landing page state.

Structural counts (units, roles, skills, workflows, principles, tools by status,
knowledge packs) come from the code and are checked on every PR against the
generated block in docs/ROADMAP.md. The test count is a release snapshot: it is
collected only by --release and kept, with the version, in site/stats.json,
which is also where the landing page gets every number. Before a release writes
anything, it also checks the page's two hand-written org mirrors (the org figure's
division names and the role titles in the hero's plan excerpt) against the code;
a mismatch fails --release only (M59). See docs/STATUS_DOCS.md.

    python scripts/status.py            print the counts and any drift
    python scripts/status.py --check    exit 1 if the roadmap or the site disagree
    python scripts/status.py --write    rewrite the roadmap block
    python scripts/status.py --release  check the org mirrors; collect tests; write
                                        stats.json, the site, the block

Run with PYTHONPATH=src or an installed package.
"""

from __future__ import annotations

import argparse
import html as htmllib
import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROADMAP = ROOT / "docs" / "ROADMAP.md"
STATS = ROOT / "site" / "stats.json"
SITE = ROOT / "site" / "index.html"

BEGIN = "<!-- status:begin (generated by scripts/status.py --write; do not edit by hand) -->"
END = "<!-- status:end -->"

# Every structural count, with the label the roadmap block gives it.
STRUCTURAL = {
    "units": "Organizational units",
    "roles": "Derived roles",
    "skills": "Skills",
    "workflows": "Workflows",
    "principles": "Constitution principles",
    "tools_available": "Tools `AVAILABLE`",
    "tools_contract_only": "Tools `CONTRACT_ONLY`",
    "knowledge_packs": "Verification knowledge packs",
}

TILE = re.compile(
    r'(<span class="stat__num" data-stat="(?P<key>\w+)" data-count=")(?P<count>\d+)(">)(?P<shown>\d+)(<)'
)


def structural_counts() -> dict[str, int]:
    from nirmaan.company import build_organization
    from nirmaan.models.org import ToolStatus
    from veritriage.knowledge.registry import available_packs

    org = build_organization()
    stats = org.stats()
    tools = list(org.tools.values())
    return {
        "units": stats["units"],
        "roles": stats["roles"],
        "skills": stats["skills"],
        "workflows": stats["workflows"],
        "principles": stats["principles"],
        "tools_available": sum(t.status is ToolStatus.AVAILABLE for t in tools),
        "tools_contract_only": sum(t.status is ToolStatus.CONTRACT_ONLY for t in tools),
        "knowledge_packs": len(available_packs()),
    }


def collect_test_count() -> int:
    """Every test pytest collects: the suite CI runs, PD-only and SDK tests included."""
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q", "-o", "addopts=", "-p", "no:cacheprovider"],
        cwd=ROOT, capture_output=True, text=True, check=False,
    )
    match = re.search(r"^(\d+) tests? collected", result.stdout, re.M)
    if not match:
        raise SystemExit(f"could not count tests:\n{result.stdout[-2000:]}{result.stderr[-2000:]}")
    return int(match.group(1))


def version() -> str:
    return tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]["version"]


def load_stats() -> dict:
    return json.loads(STATS.read_text(encoding="utf-8"))


# --- The roadmap block ---------------------------------------------------------------


def roadmap_block(counts: dict[str, int], stats: dict) -> str:
    rows = [f"| {label} | {counts[key]} | `{key}`, every PR |" for key, label in STRUCTURAL.items()]
    rows.append(f"| Tests collected | {stats['tests']} | `tests`, at release (v{stats['version']}) |")
    return "\n".join([BEGIN, "| Count | Value | Key, checked |", "|---|---|---|", *rows, END])


def _current_block(text: str) -> str:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"{ROADMAP.relative_to(ROOT)}: no status block between the markers")
    return text[start:end + len(END)]


def check_roadmap() -> list[str]:
    counts, stats = structural_counts(), load_stats()
    shown = _current_block(ROADMAP.read_text(encoding="utf-8"))
    problems = []
    for line_now, line_shown in zip(roadmap_block(counts, stats).splitlines(), shown.splitlines()):
        if line_now != line_shown:
            key = re.search(r"`(\w+)`, ", line_now)
            problems.append(f"docs/ROADMAP.md says {line_shown!r}, the code says {line_now!r}"
                            f" ({key.group(1) if key else 'block'}): run scripts/status.py --write")
    if not problems and len(shown.splitlines()) != len(roadmap_block(counts, stats).splitlines()):
        problems.append("docs/ROADMAP.md status block has the wrong rows: run scripts/status.py --write")
    return problems


def write_roadmap() -> None:
    text = ROADMAP.read_text(encoding="utf-8")
    ROADMAP.write_text(text.replace(_current_block(text), roadmap_block(structural_counts(), load_stats())),
                       encoding="utf-8")


# --- The landing page ----------------------------------------------------------------


def check_site() -> list[str]:
    """The page's tiles against stats.json only: the code is not consulted."""
    stats, html = load_stats(), SITE.read_text(encoding="utf-8")
    tiles = list(TILE.finditer(html))
    problems = [] if tiles else ["site/index.html has no data-stat tiles"]
    for tile in tiles:
        key = tile["key"]
        if key not in stats:
            problems.append(f"site tile {key!r} is not in site/stats.json")
        elif not int(tile["count"]) == int(tile["shown"]) == stats[key]:
            problems.append(f"site tile {key!r} shows {tile['shown']} (data-count {tile['count']}),"
                            f" site/stats.json says {stats[key]}: run scripts/status.py --release")
    return problems


def write_site(stats: dict) -> None:
    html = SITE.read_text(encoding="utf-8")
    html = TILE.sub(lambda m: f"{m[1]}{stats[m['key']]}{m[4]}{stats[m['key']]}{m[6]}", html)
    SITE.write_text(html, encoding="utf-8")


# --- The page's org mirrors (M59): checked at release, never per PR -----------------------

FIGURE = re.compile(r'<ul class="org__divs"[^>]*>(?P<body>.*?)</ul>', re.S)
FIGURE_ITEM = re.compile(r"<li\b[^>]*>(?P<name>.*?)</li>", re.S)
HERO = re.compile(r'<pre class="term__body"[^>]*>(?P<body>.*?)</pre>', re.S)
HERO_REQUEST = re.compile(r'<span data-type>nirmaan plan "(?P<request>[^"]+)"</span>')
# A role title in the hero: after the program-manager label, "(lead: " or "owner: ".
HERO_TITLE = re.compile(r"(?:PROGRAM MANAGER</b>\s+|\(lead: |owner: )(?P<title>[^<()]+?)\s*(?:\)|</span>)")
# The same three places in `nirmaan plan` output, where each title is followed by its role id.
PLAN_TITLE = re.compile(r"(?:PROGRAM MANAGER\s+|\(lead: |owner: )(?P<title>[^()]+?) \([\w.]+\)")


class MirrorMismatch(Exception):
    """The page's org figure or plan excerpt disagrees with the code: the release stops."""

    def __init__(self, problems: list[str]) -> None:
        super().__init__("\n".join(problems))
        self.problems = problems


def _text(fragment: str) -> str:
    return htmllib.unescape(re.sub(r"<[^>]+>", "", fragment)).strip()


def figure_divisions(page: str) -> list[str]:
    """The division names the page's org figure shows, in page order."""
    figure = FIGURE.search(page)
    return [_text(m["name"]) for m in FIGURE_ITEM.finditer(figure["body"])] if figure else []


def code_divisions() -> list[str]:
    """What the figure stands for: the active divisions outside the business function.

    The caption says the executive office and the business divisions are left out.
    """
    from nirmaan.company import build_organization
    from nirmaan.models.org import Function, UnitKind, UnitStatus

    return [u.name for u in build_organization().units.values()
            if u.kind is UnitKind.DIVISION and u.status is UnitStatus.ACTIVE
            and u.function is not Function.BUSINESS]


def hero_excerpt(page: str) -> tuple[str | None, list[str]]:
    """The request the hero's excerpt plans, and every role title it shows."""
    hero = HERO.search(page)
    if not hero:
        return None, []
    request = HERO_REQUEST.search(hero["body"])
    titles = [htmllib.unescape(m["title"]).strip() for m in HERO_TITLE.finditer(hero["body"])]
    return (htmllib.unescape(request["request"]) if request else None), titles


def plan_titles(request: str) -> set[str]:
    """Every role title `nirmaan plan REQUEST` prints: the same plan and view the CLI uses."""
    from nirmaan.company import build_organization
    from nirmaan.orchestrator import Orchestrator
    from nirmaan.views import plan_tree

    org = build_organization()
    lines = plan_tree(org, Orchestrator(org).plan(request).state)
    return {m["title"] for line in lines for m in PLAN_TITLE.finditer(line)}


def check_mirrors(page: str) -> list[str]:
    """The page's hand-written org mirrors against the code. Run by --release only."""
    problems = []
    shown, built = figure_divisions(page), code_divisions()
    if not shown:
        problems.append("site/index.html has no org figure (ul.org__divs)")
    else:
        for name in shown:
            if name not in built:
                problems.append(f"org figure shows division {name!r}, which the organization does not build")
        for name in built:
            if name not in shown:
                problems.append(f"org figure is missing division {name!r}, which the organization builds")
    request, titles = hero_excerpt(page)
    if request is None or not titles:
        problems.append("site/index.html has no hero plan excerpt with a request and role titles")
    else:
        real = plan_titles(request)
        for title in dict.fromkeys(titles):
            if title not in real:
                problems.append(f"hero excerpt shows role {title!r}, which `nirmaan plan {request!r}`"
                                " does not print")
    return problems


def release() -> dict:
    problems = check_mirrors(SITE.read_text(encoding="utf-8"))
    if problems:
        raise MirrorMismatch(problems)
    stats = {"version": version(), **structural_counts(), "tests": collect_test_count()}
    STATS.write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")
    write_site(stats)
    write_roadmap()
    return stats


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 on drift")
    mode.add_argument("--write", action="store_true", help="rewrite the roadmap block")
    mode.add_argument("--release", action="store_true", help="snapshot every count, tests included")
    args = parser.parse_args(argv)

    if args.release:
        try:
            print(json.dumps(release(), indent=2))
        except MirrorMismatch as exc:
            for problem in exc.problems:
                print(problem, file=sys.stderr)
            print("release stopped, nothing written: update the page copy in site/index.html"
                  " (see docs/STATUS_DOCS.md, section 9)", file=sys.stderr)
            return 1
        return 0
    if args.write:
        write_roadmap()
        return 0
    for key, value in structural_counts().items():
        print(f"{key:22} {value}")
    stats = load_stats()
    print(f"{'tests':22} {stats['tests']} (at v{stats['version']}, from site/stats.json)")
    problems = check_roadmap() + check_site()
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems and args.check else 0


if __name__ == "__main__":
    sys.exit(main())
