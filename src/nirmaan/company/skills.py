"""The skill catalog: reusable engineering know-how, held by roles.

Skills are composable (``includes``) and never duplicated per agent. Domain
knowledge is not re-written here either: where VeriTriage already ships a
Knowledge Pack (AXI, NoC, UVM, SVA, CDC, formal, DFT, ...), the skill cites it
as a knowledge source, and the integration test proves every cited pack exists.
"""

from __future__ import annotations

from nirmaan.models import KnowledgeSource, KnowledgeSourceKind, Skill


def _src(kind: KnowledgeSourceKind, refs: tuple[str, ...]) -> tuple[KnowledgeSource, ...]:
    return tuple(KnowledgeSource(kind=kind, ref=r, title=r) for r in refs)


def sk(
    id: str,
    name: str,
    domain: str,
    subdomain: str = "",
    *,
    provides: tuple[str, ...] = (),
    includes: tuple[str, ...] = (),
    prereq: tuple[str, ...] = (),
    packs: tuple[str, ...] = (),
    specs: tuple[str, ...] = (),
    standards: tuple[str, ...] = (),
    procedures: tuple[str, ...] = (),
    tools: tuple[str, ...] = (),
    constraints: tuple[str, ...] = (),
    fails: tuple[str, ...] = (),
    valid: tuple[str, ...] = (),
    examples: tuple[str, ...] = (),
) -> Skill:
    return Skill(
        id=id,
        name=name,
        domain=domain,
        subdomain=subdomain,
        provides=provides,
        includes=includes,
        prerequisites=prereq,
        knowledge_sources=(
            _src(KnowledgeSourceKind.VERITRIAGE_PACK, packs)
            + _src(KnowledgeSourceKind.SPECIFICATION, specs)
            + _src(KnowledgeSourceKind.COMPANY_STANDARD, standards)
        ),
        procedures=procedures,
        tools=tools,
        constraints=constraints,
        common_failure_modes=fails,
        validation_criteria=valid,
        examples=examples,
    )


def protocol(id: str, name: str, packs: tuple[str, ...], spec: str, fails: tuple[str, ...]) -> Skill:
    """A protocol skill: knowledge that refines routing, backed by a pack."""
    return sk(
        id, name, "protocols", "interface",
        packs=packs,
        specs=(spec,),
        prereq=("digital_design",),
        procedures=(
            f"Read the {name} specification sections for every channel in scope.",
            "Enumerate handshake, ordering, and response rules as checkable statements.",
        ),
        fails=fails,
        valid=(
            f"Every {name} rule used is cited to the specification.",
            "Ordering and handshake assumptions are written down, not implied.",
        ),
    )


